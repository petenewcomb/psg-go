// CombinerPool manages a pool of goroutines that execute combiners.
// It handles concurrency limits, spawning new goroutines, and reusing existing ones.
type CombinerPool struct {
	job *Job

	// CombinerPoolState hosts the data and core logic for managing the pool of
	// goroutines to maximize throughput with the minimum number of goroutines
	// and therefore duplication of individual combiners.
	state cpstate.CombinerPoolState

	// Work posting uses two-tier delivery via combineQueue:
	// 1. Try immediate delivery to waiting receivers
	// 2. If no waiting receiver, use sender's outbox and block if needed
	//
	// Primary goroutines register for immediate delivery, while the spare
	// goroutine uses PopFrontExcessFunc to process outboxes and shared channel
	// without registering for immediate delivery.
	//
	// Only one goroutine at a time can elect itself "spare" for scaling.
	combineQueue workq.Pending
	spareElected atomic.Bool

	combineOpMapMu sync.Mutex
	combineOpMap   map[combineOpID]any

	abandonedCombiners *activeCombinerMap

	// If there are tasks waiting to post work to combineQueue, the governor
	// will block new top-level scatters, thereby applying backpressure to
	// regulate the system.
	governor workq.Governor

	// Work that the pool has already committed to do because it was pulled from
	// combineQueue or generated by combiners
	workQueue workq.Accepted
}

// NewCombinerPool creates a new CombinerPool bound to the specified job.
//
// Panics if the job is nil or in the done state.
//
//nolint:contextcheck // background context used only for tracing
func NewCombinerPool(job *Job, options ...psgopt.CombinerPoolOption) *CombinerPool {
	traceRegion := "NewCombinerPool"
	defer trace.StartRegion(context.Background(), traceRegion).End()

	// Check if the job is done
	job.panicIfDone()

	cp := &CombinerPool{
		job: job,
	}

	trace.Logf(context.Background(), traceRegion,
		"CombinerPool=%p, job=%p, state=%p, combineQueue=%p, governor=%p, workQueue=%p",
		cp, job, &cp.state, &cp.combineQueue, &cp.governor, &cp.workQueue)

	cp.combineQueue.Init()
	cp.governor.Init()
	cp.workQueue.Init()

	// Apply default configuration
	cp.state.SetOptions(
		psgopt.WithConcurrencyBounds(0, -1), // unlimited by default
		psgopt.WithHighUtilizationThreshold(psgopt.DefaultCombinerPoolHighUtilizationThreshold),
		psgopt.WithMeasurementTimeConstant(psgopt.DefaultCombinerPoolMeasurementTimeConstant),
		psgopt.WithHistoryRetentionPeriod(psgopt.DefaultCombinerPoolHistoryRetentionPeriod),
		psgopt.WithMinThroughputROI(psgopt.DefaultCombinerPoolMinThroughputROI),
		psgopt.WithGrowthFactors(
			psgopt.DefaultCombinerPoolAggressiveGrowthFactor,
			psgopt.DefaultCombinerPoolConservativeGrowthFactor,
		),
		psgopt.WithIdleTimeout(psgopt.DefaultCombinerPoolIdleTimeout),
	)

	// Apply user options
	cp.state.SetOptions(options...)

	return cp
}

// checkInitialized panics if the CombinerPool was not properly initialized via NewCombinerPool
func (cp *CombinerPool) checkInitialized() {
	if cp.job == nil {
		panic("CombinerPool not initialized: must use NewCombinerPool")
	}
}

// combineOutboxKey returns a unique identifier for this CombinerPool for combine outbox mapping.
func (cp *CombinerPool) combineOutboxKey() outboxKey[workq.Work] {
	return cp
}

// SetOptions applies the given configuration options to the pool.
func (cp *CombinerPool) SetOptions(options ...psgopt.CombinerPoolOption) {
	cp.checkInitialized()
	cp.state.SetOptions(options...)
}

type boundCombineFunc func(
	ctx context.Context,
	cm *activeCombinerMap,
	gatherOutbox *workq.Outbox,
)

func (cp *CombinerPool) postCombine(
	ctx context.Context,
	group workq.GroupID,
	outbox *workq.Outbox,
	combineFn boundCombineFunc,
) {
	traceRegion := "CombinerPool.postCombine"

	defer trace.StartRegion(ctx, traceRegion).End()
	trace.Logf(ctx, traceRegion, "CombinerPool=%p, outbox=%p", cp, outbox)

	if cp.state.MaybeSpawnGoroutine() {
		cp.spawnNewGoroutine()
	}

	work := cp.newCombineWork(group, combineFn)

	cp.combineQueue.PushBackFunc(outbox, work, func(outbox *workq.Outbox) {
		// Fallback to slow path when outbox would block
		cp.postCombineSlow(ctx, outbox, work)
	})
}

//nolint:contextcheck // background context used only for tracing
func (cp *CombinerPool) newCombineWork(group workq.GroupID, combineFn boundCombineFunc) *combineWork {
	traceRegion := "CombinerPool.newCombineWork"

	w := combineWorkPool.Get()
	w.Init(group, cp, combineFn)

	trace.Logf(context.Background(), traceRegion, "CombinerPool=%p created %v", cp, w)
	return w
}

type combineWork struct {
	jobWork
	workq.DownstreamWork
	pool      *CombinerPool
	combineFn boundCombineFunc
}

func (w *combineWork) Init(group workq.GroupID, pool *CombinerPool, combineFn boundCombineFunc) {
	w.jobWork.Init(group, pool.job)
	w.pool = pool
	w.combineFn = combineFn
}

func (w *combineWork) Execute(ctx context.Context, ex workq.Execution) error {
	traceRegion := "combineWork.Execute"
	defer trace.StartRegion(ctx, traceRegion).End()
	trace.Logf(ctx, traceRegion, "%v", w)

	ex.Starting()
	workerCtx, meta := w.pool.job.ctxMeta(ctx)
	cw := meta.executionEnvironment.(*cpWorker)
	cw.LockAndSetQueueFunc(w.Group(), ex.Queue, nil)
	defer cw.UnlockAndResetQueueFunc()
	cw.executeCombine(workerCtx, w.combineFn)
	return nil
}

//nolint:contextcheck // background context used only for tracing
func (w *combineWork) Free() {
	traceRegion := "combineWork.Free"
	defer trace.StartRegion(context.Background(), traceRegion).End()
	trace.Logf(context.Background(), traceRegion, "%v", w)

	w.DownstreamWork.Close()
	w.jobWork.Close(w.pool.job)
	combineWorkPool.Put(w)
}

var combineWorkPool = omnipool.For[combineWork]()

func (cp *CombinerPool) postCombineSlow(
	ctx context.Context,
	outbox *workq.Outbox,
	work *combineWork,
) {
	traceRegion := "CombinerPool.postCombineSlow"
	defer trace.StartRegion(ctx, traceRegion).End()

	work.Waiting(&cp.governor)

	// We don't attempt the primary channel alone here since both fast paths
	// failed, meaning both primary and spare goroutines are likely busy. At
	// this point spillage to spare is warranted, so we use
	// first-come-first-served among whatever becomes available.

	for {
		spawnWaitCh := cp.state.ShouldSpawnGoroutine()
		if spawnWaitCh == nil {
			cp.spawnNewGoroutine()
		}

		// Block until we can post or it's time to retry
		outboxCh := outbox.Ch()
		trace.Logf(ctx, traceRegion, "entering select: outbox=%p, outboxCh=%p, spawnWaitCh=%p", outbox, outboxCh, spawnWaitCh)
		select {
		case outboxCh <- work:
			outbox.Filled()
			trace.Logf(ctx, traceRegion, "delivered work into outbox=%p, outboxCh=%p", outbox, outboxCh)
			return
		case <-spawnWaitCh:
			trace.Logf(ctx, traceRegion, "received signal from spawnWaitCh=%p", spawnWaitCh)
			// Loop to check if we need to spawn a new goroutine
		case <-ctx.Done():
			trace.Logf(ctx, traceRegion, "received context done signal")
			return
		}
	}
}

//nolint:contextcheck // goroutine will use job context
func (cp *CombinerPool) spawnNewGoroutine() {
	traceRegion := "CombinerPool.spawnNewGoroutine"
	trace.Logf(context.Background(), traceRegion,
		"CombinerPool=%p starting new goroutine", cp)
	wg := &cp.job.wg
	wg.Add(1)
	go func() {
		defer wg.Done()
		cp.goroutine()
	}()
}

func (cp *CombinerPool) goroutine() {
	var doneWg sync.WaitGroup
	doneCh := make(chan struct{})
	var doneErr error
	worker := &cpWorker{
		cp:     cp,
		doneCh: doneCh,
		doneErr: func() error {
			return doneErr
		},
		activeCombiners: &activeCombinerMap{},
	}

	traceRegion := "CombinerPool.goroutine"
	defer trace.StartRegion(context.Background(), traceRegion).End()
	trace.Logf(context.Background(), traceRegion, "CombinerPool=%p, worker=%p", cp, worker)

	j := cp.job

	// Create the base goroutine context
	ctx, cancel := context.WithCancel(j.ctx)
	ctx, _ = j.ensureCtxMeta(ctx,
		func(ctx context.Context, meta *ctxMeta) context.Context {
			meta.ctxType = combineContext
			meta.executionEnvironment = worker
			return ctx
		},
	)

	defer func() {
		trace.Logf(context.Background(), traceRegion, "canceling context")
		cancel()
		doneWg.Wait()
	}()

	// Minimize the number of channels on which this goroutine must repeatedly
	// retrieve and select to reduce contention.
	doneWg.Add(1)
	go func() {
		defer doneWg.Done()
		select {
		case <-j.state.Done():
			doneErr = ErrJobDone
		case <-ctx.Done():
			doneErr = ctx.Err()
		}
		close(doneCh)
	}()

	// Create the dedicated outbox for this combiner goroutine to emit gathers to the job
	worker.emitOutbox = OutboxFor[workq.Work](&worker.outboxMap, j.gatherOutboxKey())

	trace.Logf(ctx, traceRegion, "cpWorker=%p, combinerMap=%p, emitOutbox=%p",
		worker, &worker.activeCombiners, worker.emitOutbox)

	// This executes after the deferred call to cp.state.GoroutineExited() so
	// that cp.state.LiveGoroutineCount() will have been updated before this
	// deferred function executes and a new spare goroutine is elected.
	defer func() {
		if worker.idleTimer != nil {
			timerp.Put(worker.idleTimer)
			// If the idle timer is set, we are the spare goroutine
			cp.spareElected.Store(false)
		}
	}()

	cp.state.GoroutineStarted()
	defer cp.state.GoroutineExited()

	addWorkFn := worker.AddWork

	for {
		if worker.idleTimer == nil {
			if cp.spareElected.CompareAndSwap(false, true) {
				worker.idleTimer = timerp.Get()
				worker.idleFollowupFn = worker.idleFollowup // avoid reallocation of closure

				abandonedCombiners := cp.abandonedCombiners
				cp.abandonedCombiners = nil
				if abandonedCombiners != nil {
					worker.activeCombiners.Merge(abandonedCombiners)
					worker.activeCombiners.FlushExcess(ctx, worker.emitOutbox, cp.state.LiveGoroutineCount())
				}
			}
		}

		err := cp.workQueue.ExecuteOne(ctx, addWorkFn)
		switch {
		case err == nil:
		case errors.Is(err, workq.ErrEndOfWork):
			// End of work for this (spare) goroutine
			if worker.idleTimer == nil {
				panic("end of work received for non-spare goroutine")
			}
			if cp.state.LiveGoroutineCount() > 1 {
				trace.Logf(ctx, traceRegion, "spare goroutine exiting")
				// Stash active combiners for the next spare goroutine to pick up.
				if cp.abandonedCombiners != nil {
					panic("abandonedCombiners was not nil at end of spare goroutine")
				}
				cp.abandonedCombiners = worker.activeCombiners
				worker.activeCombiners = nil
				if worker.nextJobFlushCh != nil {
					worker.nextJobFlushCh = nil
					worker.unregisterAsJobFlusher()
				}
				return
			} else {
				trace.Logf(ctx, traceRegion, "last goroutine at end of work, flushing combiners")
				if !worker.flushAll(ctx) {
					trace.Logf(ctx, traceRegion, "last goroutine exiting")
					return
				}
				return
			}
		case errIn(err, ErrJobDone, context.Canceled, context.DeadlineExceeded):
			trace.Logf(ctx, traceRegion, "exiting with err=%v", err)
			return
		default:
			panic(fmt.Sprintf("combiner goroutine received unexpected error: %v", err))
		}
	}
}

type boundGather[T any] struct {
	pool     *omnipool.Pool[boundGather[T]]
	gatherFn psgfn.Gather[T]
	value    T
	err      error

	boundGatherFn boundGatherFunc
}

func (g *boundGather[T]) Init() {
	g.boundGatherFn = g.execute
}

func (g *boundGather[T]) Reset() {
	*g = boundGather[T]{
		boundGatherFn: g.boundGatherFn,
	}
}

func (g *boundGather[T]) execute(ctx context.Context) error {
	traceRegion := "boundGather.execute"
	defer trace.StartRegion(ctx, traceRegion).End()
	err := g.gatherFn(ctx, g.value, g.err)
	g.pool.Put(g)
	return err
}
